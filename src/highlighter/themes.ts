export const DEFAULT_THEME_ID = "dark-plus";

export function getTheme(id: string): Theme {
  return THEMES.find((t) => t.id === id) ?? (THEMES.find((t) => t.id === DEFAULT_THEME_ID) as Theme);
}

export function resolveStyle(theme: Theme, type: TokenType): TokenStyle {
  for (let t: TokenType | undefined = type; t; t = FALLBACK[t]) {
    const style = theme.tokens[t];
    if (style) return style;
  }
  return { color: theme.foreground };
}
