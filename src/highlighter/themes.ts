import type { TokenType } from "./types";

export interface TokenStyle {
  color: string;
  bold?: boolean;
  italic?: boolean;
}

export interface Theme {
  id: string;
  name: string;
  dark: boolean;
  background: string;
  foreground: string;
  tokens: Partial<Record<TokenType, TokenStyle>>;
}

